import { sendReviewChatMessage, fetchPastReviews } from "../../lib/api";

export interface ReviewChatProps {
  reviewId?: string;
  className?: string;
}

export interface ChatSession {
  id: string;
  reviewId?: string;
  title: string;
  time: string;
  query: string;
  messages: ChatMessage[];
}

