export const ReviewChat: React.FC<ReviewChatProps> = ({ reviewId, className = "" }) => {
  const [sessions, setSessions] = useState<ChatSession[]>(INITIAL_DEMO_SESSIONS);
  const [activeSessionId, setActiveSessionId] = useState<string>("demo-session-1");
  const [searchChatsQuery, setSearchChatsQuery] = useState("");
  const [inputQuery, setInputQuery] = useState("");
  const [isLoading, setIsLoading] = useState(false);
  const [expandedSources, setExpandedSources] = useState<Record<string, boolean>>({});
  const [copiedExport, setCopiedExport] = useState(false);
  const [isSidebarOpen, setIsSidebarOpen] = useState(true);

  const messagesEndRef = useRef<HTMLDivElement | null>(null);
  const inputRef = useRef<HTMLInputElement>(null);
  const abortControllerRef = useRef<AbortController | null>(null);

  // Fetch past reviews from backend to populate real user sessions alongside demo sessions
  useEffect(() => {
    let isMounted = true;
    fetchPastReviews(20)
      .then((reviews: ReviewHistoryItem[]) => {
        if (!isMounted || !Array.isArray(reviews) || reviews.length === 0) return;

        const backendSessions: ChatSession[] = reviews
          .filter((r) => r.status === "completed")
          .map((r) => ({
            id: `review-${r.id}`,
            reviewId: r.id,
            title: r.query.length > 36 ? `${r.query.slice(0, 36)}...` : r.query,
            time: r.created_at ? new Date(r.created_at).toLocaleDateString([], { month: "short", day: "numeric" }) : "Recent",
            query: r.query,
            messages: [
              {
                id: `welcome-${r.id}`,
                role: "assistant",
                content: `Hello! I am grounded in the research papers retrieved and synthesized for "${r.query}". Ask me anything about specific methodologies, evidence comparisons, or key findings.`,
                timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
                citations: [],
              },
            ],
          }));

        if (backendSessions.length > 0) {
          setSessions(() => {
            return [...backendSessions, ...INITIAL_DEMO_SESSIONS];
          });

          // If a reviewId was provided as a prop, select its corresponding session
          if (reviewId) {
            const matching = backendSessions.find((s) => s.reviewId === reviewId);
            if (matching) {
              setActiveSessionId(matching.id);
            }
          }
        }
      })
      .catch((err) => {
        console.warn("Could not load past reviews for chat sidebar:", err);
      });

    return () => {
      isMounted = false;
    };
  }, [reviewId]);

  // If reviewId prop is specified or changes, switch to or create that review session
  useEffect(() => {
    if (!reviewId) return;
    const matchingSession = sessions.find((s) => s.reviewId === reviewId || s.id === `review-${reviewId}`);
    if (matchingSession) {
      setActiveSessionId(matchingSession.id);
    } else {
      // Create new session for this active reviewId
      const newSess: ChatSession = {
        id: `review-${reviewId}`,
        reviewId,
        title: `Review #${reviewId}`,
        time: "Active",
        query: `Literature Review #${reviewId}`,
        messages: [
          {
            id: `welcome-${reviewId}`,
            role: "assistant",
            content: `Hello! I am your research assistant grounded in the literature reviewed for Review #${reviewId}. Ask me anything about the analyzed papers.`,
            timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
            citations: [],
          },
        ],
      };
      setSessions((prev) => [newSess, ...prev]);
      setActiveSessionId(newSess.id);
    }
  }, [reviewId]);

  const activeSession: ChatSession = useMemo(() => {
    const found = sessions.find((s) => s.id === activeSessionId);
    if (found) return found;
    if (sessions.length > 0 && sessions[0]) return sessions[0];
    return INITIAL_DEMO_SESSIONS[0] as ChatSession;
  }, [sessions, activeSessionId]);

  const filteredSessions = useMemo(() => {
    const q = searchChatsQuery.trim().toLowerCase();
    if (!q) return sessions;
    return sessions.filter(
      (s) => s.title.toLowerCase().includes(q) || s.query.toLowerCase().includes(q)
    );
  }, [sessions, searchChatsQuery]);

  const scrollToBottom = () => {
    messagesEndRef.current?.scrollIntoView({ behavior: "smooth" });
  };

  useEffect(() => {
    scrollToBottom();
  }, [activeSession?.messages, isLoading]);

  const toggleSources = (msgId: string) => {
    setExpandedSources((prev) => ({ ...prev, [msgId]: !prev[msgId] }));
  };

  const handleNewChat = () => {
    const newId = `session-${Date.now()}`;
    const newSession: ChatSession = {
      id: newId,
      title: "New Research Discussion",
      time: "Just now",
      query: "General Literature Inquiry",
      messages: [
        {
          id: `welcome-${newId}`,
          role: "assistant",
          content:
            "Hello! I am ready to explore academic literature with you. What research questions or papers would you like to investigate?",
          timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
          citations: [],
        },
      ],
    };
    setSessions((prev) => [newSession, ...prev]);
    setActiveSessionId(newId);
    inputRef.current?.focus();
  };

  const handleExportChat = () => {
    if (!activeSession) return;
    let md = `# ${activeSession.title}\n`;
    md += `*Topic: ${activeSession.query} | Date: ${activeSession.time}*\n\n---\n\n`;

    activeSession.messages.forEach((m) => {
      const sender = m.role === "user" ? "You" : "Scholaris Assistant";
      md += `### ${sender} (${m.timestamp || ""})\n\n${m.content}\n\n`;
      if (m.citations && m.citations.length > 0) {
        md += `#### Sources & Citations:\n`;
        m.citations.forEach((c, idx) => {
          md += `- [${idx + 1}] **${c.title || `Paper #${c.paper_id}`}** (${c.section_name}): "${c.snippet}"\n`;
        });
        md += `\n`;
      }
    });

    const blob = new Blob([md], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    const filename = `${activeSession.title.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-chat.md`;
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);

    if (navigator.clipboard?.writeText) {
      navigator.clipboard.writeText(md).catch(() => {});
    }
    setCopiedExport(true);
    window.setTimeout(() => setCopiedExport(false), 2000);
  };

  const handleSend = async (e: React.FormEvent) => {
    e.preventDefault();
    const trimmed = inputQuery.trim();
    if (!trimmed || isLoading || !activeSession) return;

    const timeStr = new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });
    const turnId = `turn-${Date.now()}`;
    const userMsg: ChatMessage = {
      id: `u-${Date.now()}`,
      turnId,
      role: "user",
      content: trimmed,
      status: "pending",
      timestamp: timeStr,
    };

    // Append user message immediately
    const updatedMessages = [...activeSession.messages, userMsg];
    setSessions((prev) =>
      prev.map((s) => (s.id === activeSession.id ? { ...s, messages: updatedMessages, time: "Just now" } : s))
    );
    setInputQuery("");
    setIsLoading(true);

    const controller = new AbortController();
    abortControllerRef.current = controller;

    // Build history payload for backend RAG
    const successfulTurnIds = new Set(
      activeSession.messages
        .filter((m) => m.role === "assistant" && !m.isError && m.turnId)
        .map((m) => m.turnId as string)
    );
    const historyPayload: ChatHistoryMessage[] = activeSession.messages
      .filter((m) => !m.isError && m.turnId && successfulTurnIds.has(m.turnId))
      .map((m) => ({ role: m.role, content: m.content }));

    const activeReviewId = activeSession.reviewId || reviewId;
    const isNumericReview = activeReviewId && /^\d+$/.test(activeReviewId);

    try {
      if (isNumericReview) {
        // Send to real backend pgvector RAG endpoint
        const res = await sendReviewChatMessage(activeReviewId, trimmed, historyPayload, controller.signal);
        const assistantMsg: ChatMessage = {
          id: `a-${Date.now()}`,
          turnId,
          role: "assistant",
          content: res.answer || "No response generated.",
          citations: res.citations || [],
          status: "success",
          timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
        };

        setSessions((prev) =>
          prev.map((s) => {
            if (s.id !== activeSession.id) return s;
            const finalized = s.messages.map((m) => (m.turnId === turnId ? { ...m, status: "success" as const } : m));
            return { ...s, messages: [...finalized, assistantMsg] };
          })
        );
      } else {
        // Simulate grounded academic response for demo/exploratory sessions
        await new Promise((resolve) => setTimeout(resolve, 900));

        const isRiskQuery = /risk|challenge|disadvantage|problem|concern/i.test(trimmed);
        const demoAnswer = isRiskQuery
          ? `Analysis of student cohort evaluations indicates distinct pedagogical trade-offs when integrating automated reasoning tools into academic workflows.

### What the evidence suggests
• **Critical thinking friction:** Students with unrestricted access demonstrated a tendency to accept generated explanations without verifying intermediate computational steps. [1]
• **Equity and accessibility:** Variations in student device capabilities and institutional API limits impacted collaborative problem-solving exercises. [2]`
          : `Synthesized findings demonstrate measurable gains in formative assessment benchmarks when adaptive guidance is paired with structured curricular milestones.

### What the evidence suggests
• **Targeted scaffolding:** Real-time feedback loops helped students identify conceptual misalignments 35% faster than delayed weekly office hours. [1, 2]
• **Iterative mastery:** Repeated interaction with grounded citations fostered stronger cross-domain synthesis in subsequent literature reviews. [3]`;

        const demoCitations: CitationSource[] = [
          {
            paper_id: 101,
            title: "Evaluating Interactive Academic Assistants in Undergraduate Curricula",
            section_name: "Empirical Results",
            chunk_index: 1,
            snippet:
              "Formative testing revealed accelerated comprehension of foundational principles when students received contextual hints grounded in verified lecture corpus material.",
          },
          {
            paper_id: 102,
            title: "Automated Feedback Loops and Pedagogical Outcomes",
            section_name: "Discussion & Findings",
            chunk_index: 3,
            snippet:
              "Iterative conversational engagement with source-linked citation snippets reduced ambiguity across complex technical problem assignments.",
          },
        ];

        const assistantMsg: ChatMessage = {
          id: `a-${Date.now()}`,
          turnId,
          role: "assistant",
          content: demoAnswer,
          citations: demoCitations,
          status: "success",
          timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
        };

        setSessions((prev) =>
          prev.map((s) => {
            if (s.id !== activeSession.id) return s;
            const finalized = s.messages.map((m) => (m.turnId === turnId ? { ...m, status: "success" as const } : m));
            return { ...s, messages: [...finalized, assistantMsg] };
          })
        );
      }
    } catch (err: unknown) {
      if (err instanceof Error && err.name === "AbortError") return;

      const errorMsg: ChatMessage = {
        id: `err-${Date.now()}`,
        turnId,
        role: "assistant",
        content:
          err instanceof Error && err.message
            ? err.message
            : "I encountered an issue retrieving grounded evidence from the knowledge base. Please try again.",
        isError: true,
        status: "error",
        timestamp: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
      };

      setSessions((prev) =>
        prev.map((s) => {
          if (s.id !== activeSession.id) return s;
          const finalized = s.messages.map((m) => (m.turnId === turnId ? { ...m, status: "error" as const } : m));
          return { ...s, messages: [...finalized, errorMsg] };
        })
      );
    } finally {
      setIsLoading(false);
    }
  };

  /**
   * Helper to render markdown-like formatted text with bold leads and section headings
   */
  const renderFormattedText = (content: string) => {
    const lines = content.split("\n");
    return lines.map((line, i) => {
      const trimmed = line.trim();
      if (!trimmed) {
        return <div key={`empty-${i}`} className="h-2" />;
      }

      if (trimmed.startsWith("### ")) {
        return (
          <h4 key={`h3-${i}`} className="font-bold text-xs sm:text-sm text-neutral-900 mt-2.5 mb-1.5">
            {trimmed.replace(/^###\s+/, "")}
          </h4>
        );
      }

      if (trimmed.startsWith("• ") || trimmed.startsWith("- ")) {
        const itemText = trimmed.replace(/^[•-]\s+/, "");
        // Highlight bold leads e.g. **Title:**
        const parts = itemText.split(/(\*\*.*?\*\*)/g);
        return (
          <div key={`li-${i}`} className="flex items-start gap-1.5 text-xs sm:text-sm text-neutral-800 leading-relaxed mb-1.5">
            <span className="text-neutral-400 select-none">•</span>
            <div className="flex-1">
              {parts.map((p, pIdx) => {
                if (p.startsWith("**") && p.endsWith("**")) {
                  return (
                    <strong key={pIdx} className="font-semibold text-neutral-900">
                      {p.slice(2, -2)}
                    </strong>
                  );
                }
                return <span key={pIdx}>{p}</span>;
              })}
            </div>
          </div>
        );
      }

      return (
        <p key={`p-${i}`} className="text-xs sm:text-sm text-neutral-800 leading-relaxed mb-2">
          {trimmed}
        </p>
      );
    });
  };

  return (
    <div className={`w-full max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-4 sm:py-6 ${className}`}>
      {/* Page Title & Subtitle Banner */}
      <div className="mb-6 sm:mb-8">
        <h1 className="font-serif text-3xl sm:text-4xl lg:text-[42px] font-bold text-neutral-950 tracking-tight leading-none">
          Chat with your research
        </h1>
        <p className="text-xs sm:text-sm text-neutral-600 mt-2">
          Ask better questions. Follow the evidence. Keep every source in view.
        </p>
      </div>

      {/* Two-Column Chat Grid Layout */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-start">
        {/* Left Column: "Your chats" Sidebar */}
        {isSidebarOpen && (
          <aside className="lg:col-span-4 xl:col-span-3.5 bg-white rounded-2xl border border-neutral-200/90 shadow-xs p-4 sm:p-4.5 flex flex-col gap-3.5 w-full">
            {/* Sidebar Top Header */}
            <div className="flex items-center justify-between">
              <h2 className="font-bold text-sm sm:text-base text-neutral-900">Your chats</h2>
              <button
                type="button"
                aria-label="Toggle sidebar"
                onClick={() => setIsSidebarOpen(false)}
                className="text-neutral-400 hover:text-neutral-600 transition-colors p-1 rounded-md hover:bg-neutral-100 cursor-pointer lg:hidden"
              >
                <PanelLeftClose className="w-4 h-4" />
              </button>
            </div>

            {/* + New chat Button */}
            <button
              type="button"
              onClick={handleNewChat}
              className="w-full bg-neutral-950 hover:bg-neutral-800 text-white font-medium text-xs sm:text-sm py-2.5 px-4 rounded-xl flex items-center justify-center gap-1.5 transition-colors cursor-pointer shadow-xs"
            >
              <span>+ New chat</span>
            </button>

            {/* Search Chats Input */}
            <div className="relative flex items-center">
              <Search className="w-3.5 h-3.5 text-neutral-400 absolute left-3 pointer-events-none" />
              <input
                type="text"
                placeholder="Search chats"
                value={searchChatsQuery}
                onChange={(e) => setSearchChatsQuery(e.target.value)}
                className="w-full pl-8 pr-3 py-2 text-xs bg-white border border-neutral-200 rounded-lg text-neutral-800 placeholder-neutral-400 focus:outline-none focus:ring-1 focus:ring-neutral-400"
              />
            </div>

            {/* Chats List */}
            <div className="space-y-2 mt-1 max-h-[520px] overflow-y-auto pr-0.5">
              {filteredSessions.map((s) => {
                const isActive = s.id === activeSession.id;
                return (
                  <button
                    key={s.id}
                    type="button"
                    onClick={() => setActiveSessionId(s.id)}
                    className={`w-full text-left p-3 rounded-xl transition-all cursor-pointer flex flex-col gap-1 border ${
                      isActive
                        ? "bg-[#f4fae9] border-[#cce3a5] text-neutral-900 shadow-2xs"
                        : "bg-white border-neutral-200/80 text-neutral-700 hover:bg-neutral-50/80"
                    }`}
                  >
                    <div className="flex items-start gap-2">
                      <FileText
                        className={`w-3.5 h-3.5 shrink-0 mt-0.5 ${
                          isActive ? "text-[#3b6b19]" : "text-neutral-400"
                        }`}
                      />
                      <span className="text-xs sm:text-[13px] font-semibold leading-tight line-clamp-1">
                        {s.title}
                      </span>
                    </div>
                    <span className="text-[11px] text-neutral-500 pl-5">{s.time}</span>
                  </button>
                );
              })}

              {filteredSessions.length === 0 && (
                <div className="py-6 text-center text-xs text-neutral-400">
                  No chats match &quot;{searchChatsQuery}&quot;
                </div>
              )}
            </div>
          </aside>
        )}

        {/* Right Column: Main Chat Window */}
        <main
          className={`${
            isSidebarOpen ? "lg:col-span-8 xl:col-span-8.5" : "lg:col-span-12"
          } bg-white rounded-2xl border border-neutral-200/90 shadow-xs flex flex-col h-[700px] sm:h-[750px] overflow-hidden w-full`}
        >
          {/* Chat Workspace Header */}
          <div className="px-5 sm:px-6 py-3.5 sm:py-4 border-b border-neutral-100 flex items-center justify-between bg-white shrink-0">
            <div className="min-w-0 pr-2">
              <div className="flex items-center gap-2">
                {!isSidebarOpen && (
                  <button
                    type="button"
                    onClick={() => setIsSidebarOpen(true)}
                    className="p-1 rounded-md text-neutral-500 hover:bg-neutral-100 transition-colors mr-1 cursor-pointer"
                    title="Open sidebar"
                  >
                    <PanelLeftClose className="w-4 h-4 rotate-180" />
                  </button>
                )}
                <h2 className="text-sm sm:text-base font-bold text-neutral-950 truncate">
                  Ask Questions from the Selected papers
                </h2>
              </div>
              <p className="text-[11px] sm:text-xs text-neutral-500 mt-0.5 truncate">
                {activeSession.query} / Today, {activeSession.time || "11:42 AM"}
              </p>
            </div>

            {/* Export Chat Button */}
            <button
              type="button"
              onClick={handleExportChat}
              className="px-3 py-1.5 rounded-lg border border-neutral-200 text-xs font-medium text-neutral-700 hover:bg-neutral-50 hover:text-neutral-900 transition-colors flex items-center gap-1.5 shrink-0 cursor-pointer shadow-2xs"
            >
              {copiedExport ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-600" />
                  <span>Exported</span>
                </>
              ) : (
                <>
                  <Download className="w-3.5 h-3.5 text-neutral-500" />
                  <span>Export chat</span>
                </>
              )}
            </button>
          </div>

          {/* Messages Scroll Feed */}
          <div className="flex-1 overflow-y-auto px-5 sm:px-7 py-6 space-y-6">
            {activeSession.messages.map((msg, idx) => {
              const isUser = msg.role === "user";
              const msgKey = msg.id || `msg-${idx}`;
              const isSourceOpen = expandedSources[msgKey] ?? false;
              const isErrorMessage = msg.isError ?? false;

              if (isUser) {
                return (
                  <div key={msgKey} className="flex flex-col items-end w-full">
                    <span className="text-[11px] text-neutral-400 font-medium mb-1 pr-1">
                      You · {msg.timestamp || "11:42 AM"}
                    </span>
                    <div className="bg-[#e0f0fe] border border-[#cbe4f8] text-neutral-900 rounded-2xl rounded-tr-xs px-4 sm:px-5 py-3 sm:py-3.5 text-xs sm:text-sm leading-relaxed max-w-[90%] sm:max-w-xl shadow-2xs">
                      <p className="whitespace-pre-wrap break-words">{msg.content}</p>
                    </div>
                  </div>
                );
              }

              // Assistant Message
              return (
                <div key={msgKey} className="flex flex-col items-start w-full max-w-2xl sm:max-w-3xl">
                  {/* Brand Header */}
                  <div className="flex items-center gap-1.5 mb-1.5 text-neutral-800">
                    <Sparkles className="w-3.5 h-3.5 text-[#3b6b19] fill-[#3b6b19]/20" />
                    <span className="text-xs font-bold tracking-tight text-neutral-900">Scholaris</span>
                  </div>

                  {/* Main Response Box */}
                  <div
                    className={`w-full rounded-2xl p-4 sm:p-5 ${
                      isErrorMessage
                        ? "bg-rose-50 border border-rose-200 text-rose-900"
                        : "bg-transparent text-neutral-900"
                    }`}
                  >
                    {/* Assistant Response Heading if available or synthesized */}
                    {!isErrorMessage && (
                      <h3 className="font-serif text-base sm:text-lg font-bold text-neutral-950 mb-2 leading-snug">
                        Promising support, not a substitute for teaching
                      </h3>
                    )}

                    {/* Formatted Text Content */}
                    <div className="text-xs sm:text-sm text-neutral-800">
                      {renderFormattedText(msg.content)}
                    </div>

                    {/* Sources Row: Chips [1], [2], etc. */}
                    {!isErrorMessage && msg.citations && msg.citations.length > 0 && (
                      <div className="mt-3.5 pt-3 border-t border-neutral-100">
                        <div className="flex items-center flex-wrap gap-2 text-xs text-neutral-600">
                          <span className="text-xs font-semibold text-neutral-700">Sources</span>
                          {msg.citations.map((_, cIdx) => (
                            <button
                              key={`chip-${cIdx}`}
                              type="button"
                              onClick={() => toggleSources(msgKey)}
                              className="px-2 py-0.5 rounded text-[11px] font-mono font-semibold bg-[#eefadc] text-[#2e5e14] border border-[#c4e69b] hover:bg-[#e2f7ca] transition-colors cursor-pointer"
                              title="Click to view citation snippet"
                            >
                              [{cIdx + 1}]
                            </button>
                          ))}
                          <button
                            type="button"
                            onClick={() => toggleSources(msgKey)}
                            className="text-[11px] text-neutral-400 italic hover:text-neutral-600 transition-colors cursor-pointer flex items-center gap-1 ml-1"
                          >
                            <span>Click a chip or open sources below</span>
                            {isSourceOpen ? (
                              <ChevronUp className="w-3 h-3" />
                            ) : (
                              <ChevronDown className="w-3 h-3" />
                            )}
                          </button>
                        </div>

                        {/* Expandable Grounded Source Drawer */}
                        {isSourceOpen && (
                          <div className="mt-3 space-y-2.5 max-h-72 overflow-y-auto animate-in fade-in duration-200">
                            {msg.citations.map((src, sIdx) => {
                              const displayTitle = (src.title && src.title.trim()) || `Paper #${src.paper_id}`;
                              return (
                                <div
                                  key={`src-${src.paper_id}-${sIdx}`}
                                  className="p-3 bg-neutral-50/80 rounded-xl border border-neutral-200 text-xs space-y-1.5 shadow-2xs"
                                >
                                  <div className="flex items-center justify-between gap-2 flex-wrap pb-1 border-b border-neutral-200/60">
                                    <div className="flex items-center gap-1.5">
                                      <span className="px-1.5 py-0.5 bg-[#eefadc] text-[#2e5e14] border border-[#c4e69b] rounded text-[10px] font-mono font-semibold">
                                        [{sIdx + 1}]
                                      </span>
                                      <span className="font-semibold text-neutral-900 truncate max-w-xs sm:max-w-md">
                                        {displayTitle}
                                      </span>
                                    </div>
                                    <div className="flex items-center gap-1 text-[10px]">
                                      <span className="px-1.5 py-0.5 bg-neutral-200/80 rounded font-mono text-neutral-700">
                                        Paper #{src.paper_id}
                                      </span>
                                      <span className="px-1.5 py-0.5 bg-indigo-50 text-indigo-700 rounded font-medium">
                                        {src.section_name}
                                      </span>
                                    </div>
                                  </div>
                                  <blockquote className="text-[11px] font-serif text-neutral-700 leading-relaxed bg-white p-2.5 rounded border-l-2 border-[#3b6b19] italic">
                                    &ldquo;{src.snippet}&rdquo;
                                  </blockquote>
                                </div>
                              );
                            })}
                          </div>
                        )}
                      </div>
                    )}
                  </div>
                </div>
              );
            })}

            {/* Thinking / Loading Indicator */}
            {isLoading && (
              <div className="flex flex-col items-start w-full max-w-xl">
                <div className="flex items-center gap-1.5 mb-1.5 text-neutral-800">
                  <Sparkles className="w-3.5 h-3.5 text-[#3b6b19] fill-[#3b6b19]/20" />
                  <span className="text-xs font-bold tracking-tight text-neutral-900">Scholaris</span>
                </div>
                <div className="p-3.5 bg-neutral-50 border border-neutral-200/80 rounded-2xl flex items-center gap-2">
                  <span className="w-2 h-2 rounded-full bg-neutral-400 animate-bounce" />
                  <span className="w-2 h-2 rounded-full bg-neutral-400 animate-bounce [animation-delay:0.2s]" />
                  <span className="w-2 h-2 rounded-full bg-neutral-400 animate-bounce [animation-delay:0.4s]" />
                  <span className="text-xs text-neutral-500 pl-1">Retrieving literature evidence...</span>
                </div>
              </div>
            )}
            <div ref={messagesEndRef} />
          </div>

          {/* Floating Contained Input Bar & Disclaimer */}
          <div className="px-5 sm:px-7 pb-4 pt-2 bg-white border-t border-neutral-100 shrink-0">
            <form
              onSubmit={handleSend}
              className="bg-neutral-50/90 border border-neutral-200 rounded-2xl p-2 sm:p-2.5 flex items-center justify-between gap-2 shadow-2xs focus-within:border-neutral-400 focus-within:bg-white transition-all"
            >
              <input
                ref={inputRef}
                type="text"
                placeholder="Ask a follow-up about your selected papers..."
                value={inputQuery}
                onChange={(e) => setInputQuery(e.target.value)}
                disabled={isLoading}
                className="w-full bg-transparent text-xs sm:text-sm text-neutral-800 placeholder-neutral-400 outline-none px-3 py-1"
              />
              <button
                type="submit"
                aria-label="Send question"
                disabled={!inputQuery.trim() || isLoading}
                className="w-8 h-8 sm:w-9 sm:h-9 rounded-xl bg-neutral-950 text-white hover:bg-neutral-800 disabled:opacity-30 disabled:cursor-not-allowed transition-colors flex items-center justify-center shrink-0 cursor-pointer shadow-xs"
              >
                {isLoading ? (
                  <Loader2 className="w-4 h-4 animate-spin text-white" />
                ) : (
                  <ArrowUp className="w-4 h-4 text-white" />
                )}
              </button>
            </form>

            {/* Disclaimer */}
            <p className="text-[11px] text-neutral-400 text-center mt-2.5">
              Scholaris can make mistakes. Open the cited papers to verify important claims.
            </p>
          </div>
        </main>
      </div>
    </div>
  );
};

export default ReviewChat;
